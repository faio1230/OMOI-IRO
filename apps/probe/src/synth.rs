//! Synthetic JSONL fixture generator. Output is marked `synthetic` and must
//! never be reported as a device or Live measurement.
//!
//! Scenario `mtc30-play-seek-gap` (30 NDF, run on a virtual time axis):
//!
//! | t (s) | MTC | Clock |
//! | --- | --- | --- |
//! | 0.1 | Full Frame 01:00:00:00 | |
//! | 0.5 .. 3.5 | play from 01:00:00:00 (45 sequences) | Start, 144 ticks at 120 BPM, Stop at 3.5 |
//! | 3.6 | Full Frame 01:00:10:00 (seek while stopped) | |
//! | 4.0 .. 5.0 | play from 01:00:10:00 (15 sequences) | |
//! | 5.0 .. 5.4 | no Quarter Frames (transport kept running) | |
//! | 5.4 .. 6.4 | play resumes at 01:00:11:12 (15 sequences) | |
//! | 8.0 | end | |
//!
//! Expected decoder outcome: lock at the 2nd sequence of each play segment,
//! one discontinuity of +12 frames after the gap (relock), no drops, and a
//! final `lost` + blackout snapshot at t = 8.0 s.

use omoiiro_runtime::diagnostics::record::{midi_payload, JsonlWriter};
use omoiiro_runtime::sync::mtc::{encode_full_frame, encode_quarter_frames, FrameRate, Label};
use serde_json::{json, Value};
use std::path::Path;

pub const SCENARIO: &str = "mtc30-play-seek-gap";
pub const RUN_ID: &str = "synthetic-mtc30-play-seek-gap";

struct Pending {
    t_us: i64,
    source: &'static str,
    kind: &'static str,
    payload: Value,
}

fn qf_time(t0: i64, k: i64, rate: FrameRate) -> i64 {
    // k-th quarter frame since t0, exact: k * 1e6 / (fps * 4)
    t0 + k * 1_000_000 / (rate.nominal() as i64 * 4)
}

/// Push `sequences` forward sequences starting at frame `index0` and time `t0`.
fn push_play(out: &mut Vec<Pending>, t0: i64, index0: u64, sequences: u64, rate: FrameRate) {
    for j in 0..sequences {
        let label = Label::from_frame_index(index0 + 2 * j, rate);
        let pieces = encode_quarter_frames(label);
        for (k, d) in pieces.iter().enumerate() {
            let t = qf_time(t0, (j * 8) as i64 + k as i64, rate);
            out.push(Pending { t_us: t, source: "mtc", kind: "midi", payload: midi_payload(&[0xF1, *d], t as u64) });
        }
    }
}

fn push_full_frame(out: &mut Vec<Pending>, t: i64, label: Label) {
    out.push(Pending {
        t_us: t,
        source: "mtc",
        kind: "midi",
        payload: midi_payload(&encode_full_frame(label), t as u64),
    });
}

fn push_clock(out: &mut Vec<Pending>, t0: i64, bpm: i64, beats: i64) {
    out.push(Pending { t_us: t0, source: "clock", kind: "midi", payload: midi_payload(&[0xFA], t0 as u64) });
    let ticks = beats * 24;
    for n in 0..ticks {
        // tick interval = 60e6 / (bpm * 24)
        let t = t0 + n * 60_000_000 / (bpm * 24);
        out.push(Pending { t_us: t, source: "clock", kind: "midi", payload: midi_payload(&[0xF8], t as u64) });
    }
    let t_end = t0 + ticks * 60_000_000 / (bpm * 24);
    out.push(Pending { t_us: t_end, source: "clock", kind: "midi", payload: midi_payload(&[0xFC], t_end as u64) });
}

pub fn write_fixture(path: &Path) -> std::io::Result<u64> {
    let rate = FrameRate::Fps30;
    let mut pending = Vec::new();
    pending.push(Pending {
        t_us: 0,
        source: "meta",
        kind: "synthetic",
        payload: json!({
            "scenario": SCENARIO,
            "note": "Generated by omoiiro-probe synth. Not a device or Live measurement.",
            "rate": rate.name(),
        }),
    });
    let origin = Label::new(1, 0, 0, 0, rate);
    push_full_frame(&mut pending, 100_000, origin);
    push_play(&mut pending, 500_000, origin.frame_index(), 45, rate);
    push_clock(&mut pending, 500_000, 120, 6);
    let seek = Label::new(1, 0, 10, 0, rate);
    push_full_frame(&mut pending, 3_600_000, seek);
    push_play(&mut pending, 4_000_000, seek.frame_index(), 15, rate);
    // 400 ms gap, transmitter kept running: 30 frames (1 s) + 12 frames (0.4 s)
    push_play(&mut pending, 5_400_000, seek.frame_index() + 30 + 12, 15, rate);
    pending.push(Pending { t_us: 8_000_000, source: "meta", kind: "end", payload: json!({}) });

    pending.sort_by_key(|p| p.t_us);
    let mut w = JsonlWriter::create(path, RUN_ID)?;
    for p in pending {
        w.write(p.t_us, p.source, p.kind, p.payload)?;
    }
    w.flush()?;
    Ok(w.written())
}
